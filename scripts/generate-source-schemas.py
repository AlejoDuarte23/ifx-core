import argparse
import hashlib
import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "crates/step/schema"
OUTPUT = ROOT / "crates/step/src/schema/generated"


def generate(name: str, source: dict[str, str]) -> str:
    path = ROOT / "target/schema-sources" / f"{name}.exp"
    if not path.exists():
        data = urllib.request.urlopen(source["url"], timeout=30).read()
        if hashlib.sha256(data).hexdigest() != source["sha256"]:
            raise ValueError(f"Schema download hash mismatch: {name}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    data = path.read_bytes()
    expected_hash = source["sha256"]
    if hashlib.sha256(data).hexdigest() != expected_hash:
        raise ValueError(f"Schema source hash mismatch: {name}")
    text = re.sub(r"\(\*.*?\*\)", "", data.decode("utf-8-sig"), flags=re.S)
    text = re.sub(r"--[^\r\n]*", "", text)
    entities: dict[str, tuple[str | None, list[str]]] = {}
    for entity, body in re.findall(r"\bENTITY\s+(\w+)\b(.*?)\bEND_ENTITY\s*;", text, re.I | re.S):
        head, explicit = body.split(";", 1)
        parent = re.search(r"\bSUBTYPE\s+OF\s*\(\s*(\w+)\s*\)", head, re.I)
        explicit = re.split(
            r"^\s*(?:DERIVE|INVERSE|UNIQUE|WHERE)\b", explicit, maxsplit=1, flags=re.I | re.M
        )[0]
        attrs = re.findall(r"^\s*(\w+)\s*:", explicit, re.M)
        entities[entity] = (parent.group(1) if parent else None, attrs)

    def attributes(entity: str) -> list[str]:
        parent, own = entities[entity]
        return (attributes(parent) if parent else []) + own

    lines = [
        "// Generated by scripts/generate-source-schemas.py from buildingSMART EXPRESS.",
        "// Source URLs and SHA-256 hashes: crates/step/schema/sources.json.",
        "use super::EntityDefinition;",
        "#[rustfmt::skip]",
        "pub(super) static ENTITIES: &[EntityDefinition] = &[",
    ]
    for entity in sorted(entities, key=str.upper):
        parent = entities[entity][0]
        parent_expr = f'Some("{parent.upper()}")' if parent else "None"
        attrs = ", ".join(json.dumps(a) for a in attributes(entity))
        lines.append(
            f'    EntityDefinition {{ step_name: "{entity.upper()}", name: "{entity}", '
            f"parent: {parent_expr}, attributes: &[{attrs}] }},"
        )
    lines.append("];")
    print(f"{name}: {len(entities)} entities")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    sources = json.loads((SCHEMAS / "sources.json").read_text())
    for name, source in sources.items():
        output = generate(name, source)
        path = OUTPUT / f"{name}.rs"
        if args.check:
            if path.read_text() != output:
                raise ValueError(f"Generated schema is out of date: {name}")
        else:
            path.write_text(output)


if __name__ == "__main__":
    main()
